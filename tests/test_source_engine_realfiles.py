"""Integration tests for services/source_engine against real, small synthetic
media files generated by ffmpeg — exercises the actual mediainfo/ffprobe/
mkvmerge subprocess pipeline, not just the pure-function layer covered by
test_source_engine.py.

Skipped as a whole (not failed) when ffmpeg/mediainfo/ffprobe/mkvmerge aren't
on PATH — these are real external tools, not something a test should fake,
and CI environments without them shouldn't break the build over it.

These fixtures validate that the PIPELINE works end to end and that its
results are internally coherent (always 9 candidates, always a winner, timing
within budget) — NOT that the predicted label matches some claimed ground
truth. A synthetic testsrc2 pattern encoded by libx264 always carries a hand-
encoder fingerprint, so it can't stand in for a genuine untouched WEB-DL
stream; see test_source_engine.py's transcode.py unit tests for that case.
"""
from __future__ import annotations

import shutil
import subprocess

import pytest

from emuwarez_uploadrr.services.source_engine import analyze
from emuwarez_uploadrr.services.source_engine.constants import CANDIDATES

pytestmark = pytest.mark.skipif(
    not all(shutil.which(t) for t in ("ffmpeg", "ffprobe", "mediainfo", "mkvmerge")),
    reason="ffmpeg/ffprobe/mediainfo/mkvmerge not all available in this environment",
)


def _make(tmp_path, name: str, args: list[str]) -> str:
    out = tmp_path / name
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", *args, str(out)],
        check=True, timeout=60,
    )
    return str(out)


@pytest.fixture(scope="module")
def fixtures_dir(tmp_path_factory):
    return tmp_path_factory.mktemp("source_engine_fixtures")


@pytest.fixture(scope="module")
def multi_track_mkv(fixtures_dir):
    return _make(fixtures_dir, "multi_track.mkv", [
        "-f", "lavfi", "-i", "testsrc2=size=960x540:rate=24:duration=3",
        "-f", "lavfi", "-i", "sine=frequency=440:duration=3",
        "-f", "lavfi", "-i", "sine=frequency=220:duration=3",
        "-map", "0:v", "-map", "1:a", "-map", "2:a",
        "-c:v", "libx264", "-preset", "ultrafast", "-crf", "23",
        "-c:a", "aac", "-c:a:1", "ac3",
        "-metadata:s:a:0", "language=spa", "-metadata:s:a:1", "language=eng",
    ])


