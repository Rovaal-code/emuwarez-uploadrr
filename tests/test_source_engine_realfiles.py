def test_cache_round_trip(tmp_path, plain_mp4):
    """Spec section 21: a second analysis of the same file (same size+mtime)
    must be a cache hit and skip the tools entirely."""
    from emuwarez_uploadrr import database

    conn = database.connect(tmp_path / "cache_test.db")
    database.init_db(conn)

    first = analyze(plain_mp4, use_cache=True, conn=conn)
    assert first["performance"]["cache_hit"] is False

    second = analyze(plain_mp4, use_cache=True, conn=conn)
    assert second["performance"]["cache_hit"] is True
    assert second["prediction"]["label"] == first["prediction"]["label"]
    conn.close()


def test_cache_invalidated_when_file_changes(tmp_path, fixtures_dir):
    from emuwarez_uploadrr import database

    conn = database.connect(tmp_path / "cache_test2.db")
    database.init_db(conn)

    f = fixtures_dir / "cache_invalidate.mkv"
    _make(fixtures_dir, "cache_invalidate.mkv", [
        "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=24:duration=1", "-c:v", "libx264", "-preset", "ultrafast", "-an",
    ])
    r1 = analyze(str(f), use_cache=True, conn=conn)
    assert r1["performance"]["cache_hit"] is False

    import os
    import time
    time.sleep(1.1)  # mtime resolution
    os.utime(f, None)  # touch — same size, different mtime
    r2 = analyze(str(f), use_cache=True, conn=conn)
    assert r2["performance"]["cache_hit"] is False
    conn.close()


def test_budget_exhausted_before_sampling_still_returns_result(plain_mp4):
    """Spec section 5: an exhausted budget degrades (skips sampling) rather
    than blocking the whole analysis."""
    result = analyze(plain_mp4, use_cache=False, budget_s=0.001)
    _assert_well_formed(result)
